"""Writes the generated appendix "UI glossary German → English" into AI_HANDBOOK.md (between the two markers).

The program starts in German, so users quote German UI names; the handbook uses the English ones. The glossary is
taken from sketch_machine/i18n_en.py, so it never falls behind. tests/test_handbuch.py checks that it is current.

Call in the repo root:  .venv/Scripts/python.exe packaging/handbook_glossary.py
"""
import ast
import os
import re

ROOT = os.path.abspath(os.path.join(os.path.dirname(__file__), ".."))
BOOK = os.path.join(ROOT, "AI_HANDBOOK.md")
START = "<!-- GLOSSARY:START (generated by packaging/handbook_glossary.py – do not edit by hand) -->"
END = "<!-- GLOSSARY:END -->"


def _table():
    """EN dict of i18n_en.py, read from the source (no import, no Qt)."""
    tree = ast.parse(open(os.path.join(ROOT, "sketch_machine", "i18n_en.py"), encoding="utf-8").read())
    for node in tree.body:
        if isinstance(node, ast.Assign) and any(getattr(t, "id", "") == "EN" for t in node.targets):
            return ast.literal_eval(node.value)
    raise SystemExit("EN not found in i18n_en.py")


def _clean(s):
    return re.sub(r"&(?=\w)", "", s).strip()


# Words artists use that are not UI texts (or mean two things); always listed first
TERMS = (
    ("Notizkrake, Krake", "note octopus: extra leader lines of a note to the similar parts it also means"),
    ("Ebene", "plane (tracing paper in space); in Shots also a flipbook layer (\"Ebenen\" → \"Layers\")"),
    ("Zeichenfläche", "drawing surface (curved surface you draw on)"),
    ("Fläche", "surface (fill surface, curve surface, loft)"),
    ("Strich, Linie", "stroke, line"),
    ("Stroke-Objekt", "stroke object (container of lines)"),
    ("Hinweislinie", "leader line of a note"),
    ("Notizbrett, Brett", "note board"),
    ("Kurvennetz, Netz", "curve net"),
    ("Hero-Kamera", "hero camera"),
    ("Strg / Entf / Umschalt", "Ctrl / Del / Shift"),
)


def _usable(de):
    """A UI name worth looking up: no sentence, no placeholder, no HTML, no fragment starting with a symbol."""
    return not ("\n" in de or "{" in de or "%" in de or "<" in de or len(de) > 40 or len(de.split()) > 5
                or not de[:1].isalnum())


def glossary():
    """Short UI names only (menus, buttons, tools, labels): no sentences, no placeholders."""
    rows = {}
    for de, en in _table().items():
        de, en = _clean(de), _clean(en)
        if de == en or not _usable(de):
            continue
        rows.setdefault(de, en)
    lines = [f"- **{de}** → {en}" for de, en in TERMS]
    lines += [f"- {de} → {en}" for de, en in sorted(rows.items(), key=lambda r: r[0].lower())]
    return "\n".join([START, "", *lines, "", END])


def main():
    text = open(BOOK, encoding="utf-8").read()
    a, b = text.index(START), text.index(END) + len(END)
    new = text[:a] + glossary() + text[b:]
    if new != text:
        with open(BOOK, "w", encoding="utf-8", newline="\n") as f:
            f.write(new)
    print("glossary:", glossary().count("\n- ") + 1, "entries")


if __name__ == "__main__":
    main()
