"""Introduction from the handbook pictures: docs/INTRODUCTION.md (click through on GitHub), docs/introduction.html
(slide show to open locally, arrow keys) and the block at the top of AI_HANDBOOK.md (link plus the text of every
picture, so an AI without access to the pictures knows what they show).

Source: docs/handbook/pictures.json, written by packaging/handbook_images.py. Call in the repo root after the pictures:
    .venv/Scripts/python.exe packaging/handbook_intro.py
tests/test_handbook.py checks that the handbook block is current.
"""
import html
import json
import os

ROOT = os.path.abspath(os.path.join(os.path.dirname(__file__), ".."))
DOCS = os.path.join(ROOT, "docs")
INDEX = os.path.join(DOCS, "handbook", "pictures.json")
BOOK = os.path.join(ROOT, "AI_HANDBOOK.md")
REPO = "https://github.com/felixbfx/MuleCreate/blob/main/"
START = "<!-- INTRO:START (generated by packaging/handbook_intro.py – do not edit by hand) -->"
END = "<!-- INTRO:END -->"
EXAMPLE_URL = "https://github.com/felixbfx/MuleCreate/releases/download/v0.99.255/Example_Alpaca_Monowheel.zip"
EXAMPLE = (f"Example scene to open: [Example_Alpaca_Monowheel.zip]({EXAMPLE_URL}) – sketch and finished model "
           "(USD, with and without cargo) in one scene; unzip, keep the folder together, open Alpaca_Monowheel.mule. "
           "CC BY 4.0.")
ASK_AI = ("Any question about Mule: give the file AI_HANDBOOK.md to your AI (Claude, ChatGPT, Codex …) and ask it – "
          "it describes every function, shortcut and workflow.")


def pictures():
    with open(INDEX, encoding="utf-8") as fh:
        return list(json.load(fh).values())


def _slug(heading):
    """GitHub's anchor for a heading: lower case, punctuation dropped, spaces to hyphens."""
    import re
    return re.sub(r"[^\w\- ]", "", heading.lower()).replace(" ", "-")


def _legend_md(pic):
    return [f"- **{n}** {t}" if n is not None else f"- {t}" for n, t in pic["legend"]]


def introduction_md(pics):
    out = ["# Mule Create – Introduction", "",
           f"{len(pics)} pictures of the most important functions, each from the real program. "
           "Click through with the links under each picture.", "", f"> {ASK_AI}", "", f"> {EXAMPLE}", "", "## Contents", ""]
    heads = [f"{k}. {p['title']}" for k, p in enumerate(pics, 1)]
    out += [f"{k}. [{p['title']}](#{_slug(hd)})" for k, (p, hd) in enumerate(zip(pics, heads), 1)]
    for k, (p, hd) in enumerate(zip(pics, heads), 1):
        nav = []
        if k > 1:
            nav.append(f"[← {pics[k - 2]['title']}](#{_slug(heads[k - 2])})")
        nav.append("[Contents](#contents)")
        if k < len(pics):
            nav.append(f"[{pics[k]['title']} →](#{_slug(heads[k])})")
        out += ["", f"## {hd}", "", p["summary"], "",
                f"![{p['title']}](handbook/{p['file']})", "", *_legend_md(p), "", " · ".join(nav)]
    return "\n".join(out) + "\n"


def introduction_html(pics):
    slides = "\n".join(
        f'<section class="slide" data-n="{k}"><img src="handbook/{html.escape(p["file"])}" '
        f'alt="{html.escape(p["title"] + ": " + p["summary"])}"></section>' for k, p in enumerate(pics, 1))
    return f"""<!doctype html>
<html lang="en">
<head>
<meta charset="utf-8">
<meta name="viewport" content="width=device-width, initial-scale=1">
<title>Mule Create – Introduction</title>
<style>
  :root {{ --bg: #1e1e1f; --panel: #262627; --line: #3a3a3d; --text: #e2dfda; --dim: #a9a5a0; --accent: #d08a5e; }}
  * {{ box-sizing: border-box; }}
  body {{ margin: 0; background: var(--bg); color: var(--text); font: 16px/1.5 "Segoe UI", system-ui, sans-serif; }}
  header {{ display: flex; flex-wrap: wrap; gap: 12px; align-items: center; justify-content: space-between;
           padding: 12px 16px; border-bottom: 1px solid var(--line); background: var(--panel); }}
  header h1 {{ margin: 0; font-size: 18px; color: var(--accent); }}
  header p {{ margin: 0; color: var(--dim); font-size: 14px; max-width: 70ch; }}
  nav {{ display: flex; gap: 8px; align-items: center; }}
  button {{ background: var(--line); color: var(--text); border: 0; border-radius: 6px; padding: 8px 14px;
           font: inherit; cursor: pointer; }}
  button:hover {{ background: var(--accent); color: #1e1e1f; }}
  #count {{ color: var(--dim); min-width: 5ch; text-align: center; }}
  main {{ padding: 16px; display: flex; justify-content: center; }}
  .slide {{ display: none; max-width: 1600px; width: 100%; }}
  .slide.on {{ display: block; }}
  .slide img {{ width: 100%; height: auto; border: 1px solid var(--line); border-radius: 6px; }}
</style>
</head>
<body>
<header>
  <div><h1>Mule Create – Introduction</h1><p>{html.escape(ASK_AI)}</p></div>
  <nav><button id="prev" aria-label="Previous">←</button><span id="count"></span>
  <button id="next" aria-label="Next">→</button></nav>
</header>
<main>
{slides}
</main>
<script>
  const slides = [...document.querySelectorAll('.slide')];
  let i = 0;
  function show(k) {{
    i = (k + slides.length) % slides.length;
    slides.forEach((s, j) => s.classList.toggle('on', j === i));
    document.getElementById('count').textContent = (i + 1) + ' / ' + slides.length;
    history.replaceState(null, '', '#' + (i + 1));
  }}
  document.getElementById('prev').onclick = () => show(i - 1);
  document.getElementById('next').onclick = () => show(i + 1);
  document.addEventListener('keydown', e => {{
    if (e.key === 'ArrowRight' || e.key === ' ') show(i + 1);
    if (e.key === 'ArrowLeft') show(i - 1);
  }});
  show((parseInt(location.hash.slice(1)) || 1) - 1);
</script>
</body>
</html>
"""


def handbook_block(pics):
    out = [START, "",
           f"**People: [View the introduction]({REPO}docs/INTRODUCTION.md)** – {len(pics)} pictures of the main "
           f"functions to click through (in the repository: `docs/INTRODUCTION.md`, or open "
           f"`docs/introduction.html` as a slide show). {ASK_AI}", "", EXAMPLE, "",
           "**For the AI:** the pictures in `docs/handbook/` show these steps; their text is below, so you can "
           "describe them and point the user to the right picture.", ""]
    for k, p in enumerate(pics, 1):
        legend = "; ".join((f"({n}) " if n is not None else "") + t for n, t in p["legend"])
        steps = (" Steps: " + " → ".join(p["steps"]) + ".") if p["steps"] else ""
        out.append(f"{k}. **{p['title']}** (`docs/handbook/{p['file']}`) – {p['summary']}{steps} Legend: {legend}")
    return "\n".join(out + ["", END])


def main():
    pics = pictures()
    with open(os.path.join(DOCS, "INTRODUCTION.md"), "w", encoding="utf-8", newline="\n") as fh:
        fh.write(introduction_md(pics))
    with open(os.path.join(DOCS, "introduction.html"), "w", encoding="utf-8", newline="\n") as fh:
        fh.write(introduction_html(pics))
    text = open(BOOK, encoding="utf-8").read()
    a, b = text.index(START), text.index(END) + len(END)
    new = text[:a] + handbook_block(pics) + text[b:]
    if new != text:
        with open(BOOK, "w", encoding="utf-8", newline="\n") as fh:
            fh.write(new)
    print(f"introduction: {len(pics)} pictures")


if __name__ == "__main__":
    main()
